/** "CA" for "California"; a two-letter code passes through; otherwise the first two letters. */
export function stateAbbreviation(name: string): string {
  if (Object.hasOwn(postal, name)) return postal[name];
  if (/^[A-Z]{2}$/.test(name)) return name;
  return name.slice(0, 2).toUpperCase();
}

/** Fragment for a state, exactly as writeFragment would write it ("state=New+York"). */
export const stateFragment = (state: string) =>
  new URLSearchParams({ state }).toString();
